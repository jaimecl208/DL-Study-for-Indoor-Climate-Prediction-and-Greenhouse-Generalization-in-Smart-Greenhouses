def save_experiment_json(
    filepath,
    input_variables,
    target_variable,
    model,
    optimizer,
    network_params,
    training_time,
    metrics,
    predictions,
    notes=None
):

    experiment = {
        "input_variables": input_variables,
        "target_variable": target_variable,
        "model_architecture": str(model),
        "forward_code": str(inspect.getsource(model.forward)),
        "optimizer": str(optimizer),
        "network_params": network_params,
        "training_time": training_time,
        "metrics": metrics,
        "predictions": predictions,
        "notes": notes if notes is not None else ""
    }

    os.makedirs(os.path.dirname(filepath), exist_ok=True)

    # If the file already exists -> load it
    if os.path.exists(filepath):
        with open(filepath, "r") as f:
            data = json.load(f)
    else:
        data = []

    # Append experiment
    data.append(experiment)

    # Save
    with open(filepath, "w") as f:
        json.dump(data, f, indent=4, default=str)

network_params = {
    "batch_size": batch_size,
    "lr": lr,
    "num_epochs": num_epochs,
    "patience": patience,
    "window_size": window_size,
    "horizon": horizon,
    "train_block_days": train_block_days,
    "val_block_days": val_block_days,
    "stride_train": stride_train,
    "stride_val": stride_val,
}

input_variables = input_columns
notes = ""

save_experiment_json(
    filepath=EXPERIMENT_LOG,
    input_variables=input_variables,
    target_variable=target_name,
    model=model,
    optimizer=optimizer,
    network_params=network_params,
    training_time=training_time,
    metrics=metrics,
    predictions=prediction_path,
    notes=notes
)
