"""
CNN-LSTM experiment - Álava, target: indoor relative humidity (base
variables + lags), with interleaved day-block train/val split. A 1D
convolution extracts local temporal patterns before the LSTM.

Input: processed dataset generated by
`scripts/01_preprocessing/01_preprocess_alava.py`.

Outputs:
    - Test set predictions (.parquet) in `results/predictions/alava/cnn_lstm/rel_humidity/`
    - Experiment metadata and metrics (.json) in `results/experiments/alava/cnn_lstm/rel_humidity/`
"""

