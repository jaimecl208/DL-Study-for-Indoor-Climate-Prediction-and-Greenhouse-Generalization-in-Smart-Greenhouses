INPUT_CSV = "./data/processed/Alava_processed.csv"

PREDICTIONS_DIR = "./results/predictions/alava/cnn_lstm/rel_humidity"
EXPERIMENTS_DIR = "./results/experiments/alava/cnn_lstm/rel_humidity"
EXPERIMENT_LOG = os.path.join(EXPERIMENTS_DIR, "06_cnn_lstm_alava_hum.json")

LAT = 42.8526
LON = -2.62629


def is_it_day_from_date(date, lat, lon):
    observer = ephem.Observer()
    observer.lat = str(lat)
    observer.lon = str(lon)
    observer.date = date

    sun = ephem.Sun(observer)

    return observer.previous_rising(sun) > observer.previous_setting(sun)

# ---------------------------
# Dataset
# ---------------------------
class LSTMDataset(Dataset):
    def __init__(self, X, y):
        self.X = torch.tensor(X, dtype=torch.float32)
        self.y = torch.tensor(y, dtype=torch.float32)

    def __len__(self):
        return len(self.X)

    def __getitem__(self, idx):
        return self.X[idx], self.y[idx]


# ---------------------------
# Model
# ---------------------------
class Model(nn.Module):
    def __init__(self, input_size, hidden_size, num_layers, horizon,
                 cnn_channels=32, kernel_size=3):
        super().__init__()

        self.conv1 = nn.Conv1d(
            in_channels=input_size,
            out_channels=cnn_channels,
            kernel_size=kernel_size,
            padding=kernel_size // 2,
        )
        self.tanh_cnn = nn.Tanh()

        self.lstm = nn.LSTM(
            input_size=cnn_channels,
            hidden_size=hidden_size,
            num_layers=num_layers,
            batch_first=True,
        )

        self.linear_1 = nn.Linear(hidden_size, hidden_size)
        self.tanh = nn.Tanh()
        self.fc = nn.Linear(hidden_size, horizon)

    def forward(self, x):
        x = x.permute(0, 2, 1)               # (batch, input_size, seq_len)
        x = self.tanh_cnn(self.conv1(x))         # (batch, cnn_channels, seq_len)
        x = x.permute(0, 2, 1)               # (batch, seq_len, cnn_channels)

        output, _ = self.lstm(x)
        x = output[:, -1, :]
        x = self.linear_1(x)
        x = self.tanh(x)
        return self.fc(x)


# ---------------------------
# Sequences
# ---------------------------
def prepare_sequences(df, columns, output_column, window_size, horizon, stride=1):
    """
    Generates windows (X) and output horizons (y) from a DataFrame that is
    contiguous in time.

    stride controls the offset between consecutive windows:
      - stride=1        -> overlapping windows (maximum data usage, typical for train)
      - stride=horizon  -> non-overlapping output windows (useful for validation,
                            so metrics aren't inflated by highly correlated samples)
    """
    X, y = [], []

    data = df[columns].values
    y_data = df[output_column].values

    limite = len(df) - window_size - horizon + 1
    for i in range(0, max(limite, 0), stride):
        X.append(data[i:i + window_size])
        y.append(y_data[i + window_size:i + window_size + horizon])

    return np.array(X), np.array(y)


# ---------------------------
# Interleaved day blocks (train/val)
# ---------------------------
def label_day_blocks(df, train_days=3, val_days=1):
    """
    Walks through the calendar days present in df's index and assigns each
    one the label 'train' or 'val' following a cyclic pattern:
    (train_days) days of train, (val_days) days of val, repeating for the
    whole period. Returns two Series aligned with df.index:
      - labels: 'train' / 'val' for each row
      - block_id: contiguous block identifier (changes every time the
        label changes), so sequences can be generated without crossing
        the train/val boundary.
    """
    normalized_days = pd.Series(df.index.normalize(), index=df.index)
    unique_days = sorted(normalized_days.unique())

    cycle = train_days + val_days
    label_by_day = {
        day: ("train" if (i % cycle) < train_days else "val")
        for i, day in enumerate(unique_days)
    }

    labels = normalized_days.map(label_by_day)
    block_id = (labels != labels.shift()).cumsum()

    return labels, block_id


def split_into_blocks(df, labels, block_id):
    """
    Returns a list of (label, sub_df) tuples, where each sub_df is a
    contiguous span of consecutive days with the same label ('train' or
    'val'), sorted chronologically.
    """
    blocks = []
    for bid, idx in block_id.groupby(block_id).groups.items():
        sub_df = df.loc[idx]
        label = labels.loc[idx].iloc[0]
        blocks.append((label, sub_df))

    blocks.sort(key=lambda b: b[1].index[0])
    return blocks


def generate_sequences_by_blocks(blocks, input_columns, output_column,
                                    window_size, horizon, stride):
    """
    Applies prepare_sequences to each block separately (to avoid
    crossing block boundaries) and concatenates the results.
    """
    Xs, ys = [], []
    for b in blocks:
        if len(b) < window_size + horizon:
            continue  # block too short to generate even one sequence
        Xb, yb = prepare_sequences(b, input_columns, output_column,
                                      window_size, horizon, stride=stride)
        if len(Xb) > 0:
            Xs.append(Xb)
            ys.append(yb)

    if not Xs:
        raise ValueError("Could not generate any sequence from these blocks.")

    return np.concatenate(Xs, axis=0), np.concatenate(ys, axis=0)


# ---------------------------
# Config
# ---------------------------
device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

hidden_size = 64
num_layers = 1
batch_size = 128
lr = 0.0001
num_epochs = 100
patience = 10
window_size = 12
horizon = 24

# Interleaved train/val blocks
train_block_days = 4
val_block_days = 1
stride_train = 1        # overlapping windows in train (maximum data usage)
stride_val = 1    # non-overlapping windows in validation (more honest metric)

input_columns = [
    'DB_TEMP_INT_Alava',
    'DB_TEMP_INT_Alava_lag2',
    "DB_TEMP_EXT_Alava",
    "DB_TEMP_EXT_Alava_lag2",
    "REL_HUM_EXT_Alava",
    "REL_HUM_EXT_Alava_lag2",
    "REL_HUM_INT_INPUT_Alava",
    "REL_HUM_INT_Alava_lag2",
    'is_day',
]

output_column = "REL_HUM_INT_Alava"
target_name = output_column


# ---------------------------
# Load data
# ---------------------------
df = pd.read_csv(
    INPUT_CSV,
    index_col=0,
    parse_dates=True
)

# ---------------------------
# Trainval / test split (kept chronological: test = last segment, untouched)
# ---------------------------
split_70 = int(len(df) * 0.7)
df_trainval = df.iloc[:split_70].copy()
df_test = df.iloc[split_70:].copy()

# ---------------------------
# Train / val split by interleaved day blocks within df_trainval
# ---------------------------
labels, block_id = label_day_blocks(df_trainval, train_block_days, val_block_days)
blocks = split_into_blocks(df_trainval, labels, block_id)

train_blocks = [sub_df for label, sub_df in blocks if label == "train"]
val_blocks = [sub_df for label, sub_df in blocks if label == "val"]

print(f"Train blocks: {len(train_blocks)} | Val blocks: {len(val_blocks)}")
print(f"Train rows: {sum(len(b) for b in train_blocks)} | Val rows: {sum(len(b) for b in val_blocks)}")

# ---------------------------
# Scaling (fit ONLY on the train blocks, to avoid leaking val/test information)
# ---------------------------
scaler_X = MinMaxScaler()
scaler_y = MinMaxScaler()

concatenated_train_df = pd.concat(train_blocks)
scaler_X.fit(concatenated_train_df[input_columns])
scaler_y.fit(concatenated_train_df[[output_column]])

def scale_block(sub_df):
    sub_df = sub_df.copy()
    sub_df[input_columns] = scaler_X.transform(sub_df[input_columns])
    sub_df[[output_column]] = scaler_y.transform(sub_df[[output_column]])
    return sub_df

scaled_train_blocks = [scale_block(b) for b in train_blocks]
scaled_val_blocks = [scale_block(b) for b in val_blocks]

df_test[input_columns] = scaler_X.transform(df_test[input_columns])
df_test[[output_column]] = scaler_y.transform(df_test[[output_column]])


# ---------------------------
# Sequences (generated block by block, without crossing train/val boundaries)
# ---------------------------
X_train, y_train = generate_sequences_by_blocks(
    scaled_train_blocks, input_columns, output_column, window_size, horizon, stride=stride_train
)

X_val, y_val = generate_sequences_by_blocks(
    scaled_val_blocks, input_columns, output_column, window_size, horizon, stride=stride_val
)

X_test, y_test = prepare_sequences(
    df_test, input_columns, output_column, window_size, horizon
)

print(f"Sequences -> train: {len(X_train)} | val: {len(X_val)} | test: {len(X_test)}")


# ---------------------------
# DataLoaders
# ---------------------------
train_loader = DataLoader(LSTMDataset(X_train, y_train), batch_size=batch_size, shuffle=True)
val_loader = DataLoader(LSTMDataset(X_val, y_val), batch_size=batch_size, shuffle=False)


# ---------------------------
# Model
# ---------------------------
input_size = len(input_columns)

model = Model(input_size, hidden_size, num_layers, horizon).to(device)

criterion = nn.MSELoss()
optimizer = optim.AdamW(model.parameters(), lr=lr)

scheduler = ReduceLROnPlateau(
    optimizer,
    mode="min",
    factor=0.5,      # each time it reduces, it divides the LR by 2
    patience=4,       # smaller than the early stopping patience (10)
    min_lr=1e-6
)

# ---------------------------
# Early stopping
# ---------------------------
best_val_loss = float("inf")
counter = 0


# ---------------------------
# Training
# ---------------------------
start_time = time.time()

for epoch in range(num_epochs):

    # TRAIN
    model.train()
    train_loss = 0

    for X, y_batch in tqdm(train_loader, desc=f"Epoch {epoch+1} [TRAIN]", leave=False):
        X, y_batch = X.to(device), y_batch.to(device)

        optimizer.zero_grad()
        outputs = model(X)
        loss = criterion(outputs, y_batch)
        loss.backward()
        optimizer.step()

        train_loss += loss.item()

    train_loss /= len(train_loader)

    # VALIDATION
    model.eval()
    val_loss = 0

    with torch.no_grad():
        for X, y_batch in val_loader:
            X, y_batch = X.to(device), y_batch.to(device)

            outputs = model(X)
            loss = criterion(outputs, y_batch)

            val_loss += loss.item()

    val_loss /= len(val_loader)

    scheduler.step(val_loss)
    current_lr = optimizer.param_groups[0]["lr"]

    print(f"Epoch {epoch+1}: Train={train_loss:.4f} | Val={val_loss:.4f}")

    # EARLY STOPPING
    if val_loss < best_val_loss:
        best_val_loss = val_loss
        counter = 0
    else:
        counter += 1
        if counter >= patience:
            print("Early stopping triggered")
            break

end_time = time.time()
training_time = end_time - start_time

# ---------------------------
# Evaluation
# ---------------------------
model.eval()

rows = []
step = horizon

with torch.no_grad():

    for i in range(0, len(df_test) - window_size - horizon + 1, step):

        xs = df_test[input_columns].iloc[i:i+window_size].values
        xs = torch.tensor(xs, dtype=torch.float32).unsqueeze(0).to(device)

        pred = model(xs).cpu().numpy()[0]

        actual = df_test[output_column].iloc[
            i + window_size : i + window_size + horizon
        ].values

        pred = scaler_y.inverse_transform(pred.reshape(1, -1))[0]
        actual = scaler_y.inverse_transform(actual.reshape(1, -1))[0]

        base_time = df_test.index[i + window_size]

        for h in range(horizon):
            rows.append({
                "date": base_time + pd.Timedelta(minutes=15 * (h + 1)),
                "t0": base_time,
                "actual": actual[h],
                "pred": pred[h],
                "horizon": h + 1
            })

df_eval = pd.DataFrame(rows).set_index("date").sort_index()

os.makedirs(PREDICTIONS_DIR, exist_ok=True)
prediction_path = os.path.join(PREDICTIONS_DIR, f"exp_{uuid.uuid4().hex}.parquet")
df_eval.to_parquet(prediction_path)


# ---------------------------
# Full metrics
# ---------------------------
y_true = df_eval["actual"].values
y_pred = df_eval["pred"].values

metrics = {
    "global": {
        "r2": float(r2_score(y_true, y_pred)),
        "mse": float(mean_squared_error(y_true, y_pred)),
        "rmse": float(np.sqrt(mean_squared_error(y_true, y_pred))),
        "mae": float(mean_absolute_error(y_true, y_pred)),
        "mape": float(np.mean(np.abs((y_true - y_pred) / (y_true + 1e-8))) * 100),
        "relative_error": float(np.mean((y_pred - y_true) / (y_true + 1e-8))),
        "relative_error_abs": float(np.mean(np.abs((y_pred - y_true) / (y_true + 1e-8))))
    },
    "per_horizon": {},
    "per_month": {}
}

